#!/usr/bin/env python3
"""Второй выход из того же слоя тем: что сказано владельцем и ещё не записано.

Корпус сам называет свою цель в первом же разговоре о нём: перечитать
накопленные комментарии и по ним править инструкции. Восемь стадий делают
другое — раскладывают знание по вопросам. Обе работы законны, но вторая до
сегодня не делалась вовсе, хотя вход у неё готовый: те же 40 тем.

Замер самого корпуса (`_ops/chat-recall/README.md`): 16 находок из 19 не
существуют нигде в нормативных файлах. Значит разрыв не гипотеза.

Агент судит одну тему против нормативных файлов и раскладывает её пункты на
три кучи: уже записано · противоречит записанному · нигде нет.
"""
from __future__ import annotations

import glob
import json
import os
import sys

ART = "experiments/openviking-chat-recall/artifacts"
NORMATIVE = ["AGENTS.md", "CLAUDE.md", "_ops/GOAL.md", "_ops/AGENTS.md",
             "_ops/product-frames/agentic-research.md",
             "_ops/product-frames/agentic-research.principles.md"]


def main(topics_dir: str, out_dir: str) -> int:
    core = "\n\n".join(
        f"### `{path}`\n\n```\n{open(path, encoding='utf-8').read().strip()}\n```"
        for path in NORMATIVE if os.path.exists(path)
    )
    os.makedirs(out_dir, exist_ok=True)
    written = 0
    for path in sorted(glob.glob(os.path.join(topics_dir, "*.md"))):
        topic = os.path.basename(path)[:-3]
        open(os.path.join(out_dir, topic + ".txt"), "w", encoding="utf-8").write(
            f"""Роль: ревизор инструкций. У тебя одна тема знаний владельца и нормативные
файлы проекта. Вопрос ровно один: **что из этой темы ещё нигде не записано.**

Знание владельца живёт в двух местах и они расходятся. Разговоры фиксируются
сразу, а инструкции правятся редко и вручную, поэтому корпус систематически
свежее нормативных файлов и может им прямо противоречить. Твоя работа — сделать
этот разрыв видимым и посчитанным.

## Три кучи и только они

- `записано` — пункт уже есть в нормативном файле по смыслу, пусть другими
  словами. Назови файл и раздел;
- `противоречит` — нормативный файл говорит другое. Назови оба места. Это
  самая ценная находка: расхождение живёт молча и каждая сессия разбирает его
  заново;
- `нигде` — ни один нормативный файл этого не говорит. Назови файл, куда пункт
  просился бы по смыслу, — но **не пиши текст правки**: решение о правке
  инструкции принимает владелец, не ты.

Пункт про артефакт, который уже удалён или переименован, — это `устарело`,
четвёртая куча, и её тоже называй.

## Чего не делать

Не правь ни одного файла. Не предлагай формулировок для инструкций. Не считай
пункт записанным потому, что он «в духе» файла: нужен адрес.

Часть пунктов относится к скилам, живущим за пределами репозитория
(`~/.claude/skills/`, `~/.codex/skills/`). Их текст тебе недоступен — так и
пиши `вне репо`, это честный ответ, а не пропуск. Скилы, у которых есть
tracked owner, лежат в `skills/shared/**`, `skills/claude/**`, `skills/codex/**`
и читаются.

## Формат ответа

Только строки TSV, по одной на пункт темы, без шапки и пояснений. Четыре
колонки:

```
<якорь пункта>\t<записано|противоречит|нигде|устарело|вне репо>\t<адрес: файл и раздел, либо «—»>\t<одна фраза: что именно>
```

Якорь копируй из темы посимвольно.

## Нормативные файлы проекта

{core}

## Тема

```
{open(path, encoding='utf-8').read().strip()}
```

## Стоп

Ничего не правь. Строк — ровно столько, сколько пунктов в теме.
""")
        written += 1
    print(f"заданий ревизии: {written} -> {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1] if len(sys.argv) > 1 else f"{ART}/flatten-v1/topics",
                          sys.argv[2] if len(sys.argv) > 2 else "_workspace/ox-delta/tasks"))
