#!/usr/bin/env python3
"""Структурные находки аудита: разрезанный ответ и смешанные вопросы.

Это единственное место, где модели даётся право менять состав страниц, и право
это узкое намеренно: маршрут, где агент одновременно проектировал структуру и
удерживал точность, проваливался четыре раза подряд. Здесь структура уже есть,
источник в руках, а разрешённых движений ровно два — разделить одну страницу на
две или перенести пункт между двумя названными. Больше ничего.

Агент возвращает полное новое содержимое затронутых страниц; кладёт их на место
скрипт (инвариант 2 протокола).
"""
from __future__ import annotations

import os
import sys

ART = "experiments/openviking-chat-recall/artifacts"
WIKI = f"{ART}/wiki-v1"


def main(findings: str, out_dir: str) -> int:
    os.makedirs(out_dir, exist_ok=True)
    written = 0
    for row in open(findings, encoding="utf-8"):
        topic, page, kind, what = row.rstrip("\n").split("\t", 3)
        target = os.path.join(WIKI, page)
        if not os.path.exists(target):
            print(f"  страницы нет: {page}")
            continue
        source = f"_ops/chat-recall-topics/{topic}.md"
        open(os.path.join(out_dir, f"{topic}--{os.path.basename(page)[:-3]}.txt"), "w",
             encoding="utf-8").write(
            f"""Роль: редактор библиотеки знаний. Проверяющий нашёл на одной странице
структурное расхождение. Твоя работа — исправить именно его.

## Находка

Вид: `{kind}`
Страница: `{page}`
Что не так: {what}

`смешано` — страница отвечает на два вопроса, которые будут искать порознь.
`разрезано` — ответ на один вопрос лежит на двух страницах, и с каждой уходишь
с половиной.

## Что разрешено и что нет

Разрешены ровно два движения: **разделить страницу на две** или **перенести
пункт на другую названную страницу**. Ничего больше: не переписывай пункты, не
меняй их модальность, не добавляй фактов, не трогай соседние страницы, о
которых находка не говорит.

Пункт переносится **дословно вместе со своей ссылкой**. Ссылка копируется
посимвольно; набирать её заново нельзя.

Если после разбора окажется, что находка неверна и страница цельная, — так и
скажи, это законный ответ.

## Источник темы

{open(source, encoding='utf-8').read().strip() if os.path.exists(source) else '(файл темы не найден)'}

## Текущая страница

```
{open(target, encoding='utf-8').read().strip()}
```

## Формат ответа

Сначала одна строка вердикта: `правлю` или `находка неверна: <причина>`.

Если правишь — дальше по одному блоку на каждую страницу результата, в таком
виде и без пояснений между блоками:

```
=== ФАЙЛ <тип>/<слаг>.md
<полное содержимое страницы от `---` до последней строки>
```

Первый блок — исправленная существующая страница по её нынешнему пути. Второй
блок, если он есть, — новая страница; её `topic` тот же, `type` выбери из
`entity · concept · method · comparison · analysis`, слаг латиницей.

## Стоп

Файлы не открывай и не правь — весь материал выше.
""")
        written += 1
    print(f"заданий на структурную правку: {written} -> {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1] if len(sys.argv) > 1 else f"{ART}/audit-structural.tsv",
                          sys.argv[2] if len(sys.argv) > 2 else "_workspace/ox-split/tasks"))
