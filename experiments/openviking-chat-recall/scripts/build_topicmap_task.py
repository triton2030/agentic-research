#!/usr/bin/env python3
"""Стадия 2: карта тем из строк «о чём», а не из цитат.

Владелец 2026-08-22 остановил ход, где агенты пытались построить карту по всем
файлам цитат разом: «это нереально». Стадия переписана под это: на вход идёт
каталог из имени, даты и одной строки о чём был разговор — то, что уже
посчитала стадия 1. Цитаты в эту стадию не входят вовсе.

    python3 build_topicmap_task.py <папка сжатых файлов> <папка задания>
"""
from __future__ import annotations

import glob
import os
import re
import sys


def main(flat: str, out_dir: str) -> int:
    rows = []
    for path in sorted(glob.glob(os.path.join(flat, "*.md"))):
        head = open(path, encoding="utf-8").read().split("---", 2)[1]
        get = lambda k: (re.search(rf"^{k}:\s*(.+)$", head, re.M) or [None, ""])[1].strip()
        rows.append(f"- `{os.path.basename(path)}` · {get('date')} · {get('about')}")
    os.makedirs(out_dir, exist_ok=True)
    open(os.path.join(out_dir, "topics.txt"), "w", encoding="utf-8").write(
        f"""Роль: редактор библиотеки знаний. Перед тобой каталог {len(rows)} разговоров с
владельцем проекта: имя файла, дата и одна строка о чём был разговор. Самих
разговоров ты не видишь и они тебе не нужны.

## Что сделать

Разложи файлы по темам.

Тема — **то, о чём агент однажды спросит**: устойчивый предмет работы, а не
месяц и не тип разговора. «Август» темой не является. «Обсуждения» — тоже.
Хорошая тема называет вещь, вокруг которой знание накапливается и будет
накапливаться дальше.

Каждый файл попадает ровно в одну тему. Файлов без темы не бывает: разговор,
не подошедший никуда, идёт в ближайшую по предмету, а не заводит тему из
одного файла ради аккуратности. Тему из одного файла заводи только когда
предмет действительно самостоятельный.

Число тем не задано. Ориентир: тем должно быть заметно меньше, чем файлов, и
заметно больше одной.

## Формат ответа

Только строки TSV, по одной на **файл**, без шапки и пояснений. Три колонки:

```
<имя файла как есть>\t<идентификатор темы латиницей через дефис>\t<имя темы одной строкой по-русски>
```

Идентификатор одной темы пишется одинаково во всех её строках. Имя темы тоже.
Строк ровно {len(rows)} — по одной на каждый файл каталога.

## Каталог

{chr(10).join(rows)}

## Стоп

Файлы не открывай и не правь — весь каталог выше.
""")
    print(f"каталог из {len(rows)} разговоров -> {out_dir}/topics.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1], sys.argv[2]))
