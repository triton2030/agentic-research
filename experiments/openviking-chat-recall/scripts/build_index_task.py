#!/usr/bin/env python3
"""Задание на указатель: модель называет сорок разделов, страницы ставит скрипт.

Первый заход отдал модели весь указатель целиком — каталог из трёхсот с лишним
страниц, из которого она должна была собрать двухуровневое оглавление. Прогон
шёл больше часа и не вернул ничего. Работа была не сложной, а огромной, и почти
вся — механической: путь, тип и тема каждой страницы уже решены прошлыми
стадиями.

Суждения здесь ровно на сорок строк: как назвать раздел словами читателя и в
каком порядке разделы поставить. Их и спрашиваем.
"""
from __future__ import annotations

import json
import os
import sys

ART = "experiments/openviking-chat-recall/artifacts"


def main(skeleton_path: str, out_dir: str) -> int:
    skeleton = json.load(open(skeleton_path, encoding="utf-8"))
    blocks = []
    for section in skeleton["sections"]:
        titles = "\n".join(f"     - {p['title']}" for p in section["pages"][:14])
        more = len(section["pages"]) - 14
        blocks.append(
            f"`{section['topic']}` · страниц {len(section['pages'])}\n"
            f"   рабочее имя: {section['title']}\n"
            f"   вопросы страниц:\n{titles}"
            + (f"\n     … и ещё {more}" if more > 0 else "")
        )
    os.makedirs(out_dir, exist_ok=True)
    open(os.path.join(out_dir, "index.txt"), "w", encoding="utf-8").write(
        f"""Роль: редактор указателя библиотеки знаний. Библиотека уже разложена на
{skeleton['section_count']} разделов и {skeleton['page_count']} страниц; пути и состав менять не надо.

От тебя нужны две вещи и только они: **имя каждого раздела словами читателя** и
**порядок разделов**.

## Как назвать раздел

Рабочее имя раздела — служебное, оно писалось для нас. Имя в указателе пишется
для агента, который пришёл с вопросом и ещё не знает нашего словаря. Смотри на
вопросы страниц внутри: имя должно обещать ровно то, что там лежит, и не
обещать большего.

Рядом с именем — подсказка одной строкой: строгий пересказ того, что в разделе
есть. Подсказка не добавляет ни одного факта, которого нет в вопросах страниц.

## Как упорядочить

Первым идёт то, что спросят чаще. Дальше — от общего к частному. Разделы, к
которым обращаются редко, стоят последними, но не выбрасываются.

## Формат ответа

Только строки TSV, по одной на раздел, без шапки и пояснений. Четыре колонки:

```
<порядковый номер: 1, 2, 3 …>\t<идентификатор раздела как есть>\t<имя раздела для читателя>\t<подсказка одной строкой>
```

Идентификатор копируй посимвольно — он ключ, по которому скрипт подставит
страницы. Строк должно быть ровно {skeleton['section_count']}, каждый идентификатор ровно один раз.

## Разделы

{chr(10).join(blocks)}

## Стоп

Файлы не открывай и не правь — весь материал выше.
""")
    print(f"задание на указатель: {skeleton['section_count']} разделов -> {out_dir}/index.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(
        sys.argv[1] if len(sys.argv) > 1 else f"{ART}/index-skeleton.json",
        sys.argv[2] if len(sys.argv) > 2 else "_workspace/ox-index2/tasks"))
